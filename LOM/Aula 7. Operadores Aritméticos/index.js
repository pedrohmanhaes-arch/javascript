/*Aritméticos 
 + -> Adição / Concatenação
 - -> subtração
 / -> divisão
 * -> multiplicação
 ** -> potenciação
 % -> resto da divisão
*/

/* precedencia
1) ()
2) **
3) * / %
4) + -
*/

const num1 = 5;
const num2 = 10;
console.log(num1 + num2)
console.log(num2 - num1)
console.log(num1 / num2)
console.log(num1 * num2)
console.log(num1 ** num2)
console.log(num2 % num1)

let contador = 1; //1
contador ++; //2
contador++; //3

console.log(contador)

